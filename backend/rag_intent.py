"""R6 意图解析模块：把自然语言 query 确定性映射为标签过滤条件。

/ask 的检索层此前只做字面匹配，「免费景点」「适合带孩子」「下雨天能去哪」这类
意图型查询无法转化为过滤条件。本模块补上这一步：对 query 做**确定性关键词规则**
匹配，输出命中的标签列表，供上层（rag.py 集成侧）转成语料标签过滤/加权。

标签体系与 corpus_fields.SPOT_TAGS 保持一致（13 个，固定）：
    ["免费", "亲子", "夜景", "室内", "自然风光", "历史文化", "登山徒步",
     "古镇街区", "博物馆", "寺庙宗教", "海滨", "演出", "美食"]

设计约束：
- 确定性关键词规则：query 先小写化再做包含匹配，同一输入永远同一输出；
- 零 I/O、零网络、零 LLM：纯函数，不读文件、不调接口、不跑模型，离线可跑、
  单测零 mock；
- 词表按真实语感收录常见口语说法，后续可加词（只动词表不动结构）；
- 「历史文化」关键词含「历史/古迹」等（2026-10-04 集成时补，评测集有对应 query）；
- intent_keywords() 供语料做文档扩展（标签意图词拼进文本，单一事实源仍是本模块规则表）。

用法：
    >>> parse_intent("西安有什么免费景点")
    ['免费']
    >>> parse_intent("兵马俑")
    []
"""

from __future__ import annotations

# 规则表：(标签, 触发关键词)。**顺序即多意图命中时的返回顺序**，勿随意调整。
# 包含匹配与词长无关，单字词（寺/庙）的误触发风险由 tests/test_rag_intent.py
# 的专名用例（兵马俑/乳扇等）守门。
_INTENT_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("免费", ("免费", "不要钱", "穷游", "免票", "不花钱", "不要门票", "免门票")),
    ("亲子", ("孩子", "儿童", "亲子", "带娃", "小朋友", "带孩子", "遛娃")),
    ("室内", ("下雨", "雨天", "室内", "避暑", "宅一天")),
    ("夜景", ("夜景", "晚上", "夜晚", "夜市", "夜生活", "灯火")),
    ("登山徒步", ("爬山", "登山", "徒步", "远足", "登高")),
    ("古镇街区", ("古镇", "古城", "老街", "街区")),
    ("博物馆", ("博物馆", "展馆", "看展")),
    ("寺庙宗教", ("寺", "庙", "祈福", "拜佛", "烧香")),
    ("海滨", ("海边", "海滨", "沙滩", "赶海", "海岛", "玩水")),
    ("演出", ("演出", "表演", "千古情", "看秀")),
    ("美食", ("小吃", "美食", "吃什么", "好吃的", "特色菜")),
    ("自然风光", ("风光", "风景", "山水", "自然")),
    ("历史文化", ("历史", "古迹", "文物", "遗产", "人文")),
)


def intent_keywords(tag: str) -> tuple[str, ...]:
    """某标签在规则表里的触发关键词（≥2 字的才返回——单字拼进语料会误伤）。

    供 rag.build_corpus 做「文档扩展」：把意图同义词拼进带该标签的语料文本，
    让「适合带孩子」这类意图词能直接命中亲子景点（R6，经 rag_rank_eval 实测驱动）。
    """
    for t, keywords in _INTENT_RULES:
        if t == tag:
            return tuple(k for k in keywords if len(k) >= 2)
    return ()


def parse_intent(q: str) -> list[str]:
    """解析 query 中的意图标签。

    Args:
        q: 用户原始查询（如「下雨天能去哪」）；空串/纯标点安全，返回 []。

    Returns:
        命中的标签列表，取值 ⊆ 上述 13 个标签；按规则表顺序去重，无命中返回 []。
    """
    q_lower = (q or "").lower()
    return [
        tag
        for tag, keywords in _INTENT_RULES
        if any(keyword in q_lower for keyword in keywords)
    ]
